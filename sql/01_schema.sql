DROP SCHEMA IF EXISTS scm CASCADE;
CREATE SCHEMA scm;
SET search_path TO scm, public;


CREATE TYPE user_role        AS ENUM ('admin', 'manager', 'sales', 'warehouse_worker');
CREATE TYPE product_category AS ENUM ('electronics', 'clothing');
CREATE TYPE order_status     AS ENUM ('new', 'confirmed', 'shipped', 'delivered', 'cancelled');
CREATE TYPE supply_status    AS ENUM ('planned', 'in_transit', 'delivered', 'rejected');
CREATE TYPE shipment_status  AS ENUM ('pending', 'shipped', 'delivered');


-- Системні
CREATE TABLE app_user (
    id             integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       varchar(50)  NOT NULL UNIQUE,
    password_hash  varchar(255) NOT NULL,
    role           user_role    NOT NULL,
    employee_id    integer      UNIQUE,   -- 1:1, FK нижче
    is_active      boolean      NOT NULL DEFAULT true,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_app_user_username CHECK (username ~ '^[a-zA-Z0-9_.]{3,50}$')
);
COMMENT ON TABLE app_user IS 'Користувачі системи; на них посилаються updated_by та audit_log.changed_by';

-- Структура компанії
CREATE TABLE department (
    id                integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(255) NOT NULL UNIQUE,
    phone             varchar(20),
    head_employee_id  integer      NOT NULL UNIQUE,   -- FK нижче
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz,
    updated_by        integer      REFERENCES app_user(id),
    CONSTRAINT ck_department_name CHECK (btrim(name) <> '')
);

CREATE TABLE employee (
    id             integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      varchar(255)  NOT NULL,
    position       varchar(100)  NOT NULL,
    salary         numeric(10,2) NOT NULL,
    hire_date      date          NOT NULL DEFAULT current_date,
    department_id  integer       NOT NULL REFERENCES department(id),
    mentor_id      integer       REFERENCES employee(id),
    created_at     timestamptz   NOT NULL DEFAULT now(),
    updated_at     timestamptz,
    updated_by     integer       REFERENCES app_user(id),
    deleted_at     timestamptz,
    CONSTRAINT ck_employee_full_name CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_employee_salary    CHECK (salary > 0),
    CONSTRAINT ck_employee_mentor    CHECK (mentor_id <> id)
);

-- department <-> employee посилаються одна на одну, тому FK перевіряється при COMMIT
ALTER TABLE department
    ADD CONSTRAINT fk_department_head FOREIGN KEY (head_employee_id)
        REFERENCES employee(id) DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE app_user
    ADD CONSTRAINT fk_app_user_employee FOREIGN KEY (employee_id)
        REFERENCES employee(id) ON DELETE SET NULL;

-- Клієнти та продажі
CREATE TABLE customer (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   varchar(255) NOT NULL,
    phone       varchar(20),
    email       varchar(255),
    address     text,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz,
    updated_by  integer      REFERENCES app_user(id),
    deleted_at  timestamptz,
    CONSTRAINT ck_customer_full_name CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_customer_email     CHECK (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT ck_customer_contact   CHECK (phone IS NOT NULL OR email IS NOT NULL)
);

-- Товари
CREATE TABLE product (
    sku         varchar(50)      PRIMARY KEY,
    name        varchar(255)     NOT NULL,
    price       numeric(10,2)    NOT NULL,
    category    product_category NOT NULL,   -- визначає підтип
    created_at  timestamptz      NOT NULL DEFAULT now(),
    updated_at  timestamptz,
    updated_by  integer          REFERENCES app_user(id),
    deleted_at  timestamptz,
    CONSTRAINT ck_product_sku   CHECK (sku ~ '^[A-Z0-9-]{3,50}$'),
    CONSTRAINT ck_product_name  CHECK (btrim(name) <> ''),
    CONSTRAINT ck_product_price CHECK (price >= 0)
);

CREATE TABLE electronics (
    product_sku      varchar(50) PRIMARY KEY REFERENCES product(sku) ON DELETE CASCADE,
    warranty_months  integer     NOT NULL,
    CONSTRAINT ck_electronics_warranty CHECK (warranty_months BETWEEN 0 AND 120)
);

CREATE TABLE clothing (
    product_sku  varchar(50)  PRIMARY KEY REFERENCES product(sku) ON DELETE CASCADE,
    size         varchar(20)  NOT NULL,
    material     varchar(100) NOT NULL
);

CREATE TABLE customer_order (
    order_number  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   integer      NOT NULL REFERENCES customer(id),
    employee_id   integer      NOT NULL REFERENCES employee(id),
    order_date    timestamptz  NOT NULL DEFAULT now(),
    status        order_status NOT NULL DEFAULT 'new',
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz,
    updated_by    integer      REFERENCES app_user(id)
);

-- Слабка сутність: ключ (order_number, line_number)
CREATE TABLE order_item (
    order_number  integer       NOT NULL REFERENCES customer_order(order_number) ON DELETE CASCADE,
    line_number   integer       NOT NULL,
    product_sku   varchar(50)   NOT NULL REFERENCES product(sku),
    quantity      integer       NOT NULL,
    unit_price    numeric(10,2) NOT NULL,   -- ціна на момент продажу
    PRIMARY KEY (order_number, line_number),
    CONSTRAINT ck_order_item_line     CHECK (line_number > 0),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_item_price    CHECK (unit_price >= 0)
);

-- Постачання
CREATE TABLE supplier (
    edrpou        varchar(10)  PRIMARY KEY,
    company_name  varchar(255) NOT NULL,
    phone         varchar(20),
    email         varchar(255),
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz,
    updated_by    integer      REFERENCES app_user(id),
    deleted_at    timestamptz,
    CONSTRAINT ck_supplier_edrpou CHECK (edrpou ~ '^[0-9]{8}([0-9]{2})?$'),
    CONSTRAINT ck_supplier_name   CHECK (btrim(company_name) <> '')
);

CREATE TABLE contract (
    contract_number  varchar(50) PRIMARY KEY,
    supplier_edrpou  varchar(10) NOT NULL REFERENCES supplier(edrpou),
    sign_date        date        NOT NULL,
    expiry_date      date        NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz,
    updated_by       integer     REFERENCES app_user(id),
    deleted_at       timestamptz,
    CONSTRAINT ck_contract_dates CHECK (expiry_date > sign_date)
);

CREATE TABLE contract_item (
    contract_number  varchar(50)   NOT NULL REFERENCES contract(contract_number) ON DELETE CASCADE,
    product_sku      varchar(50)   NOT NULL REFERENCES product(sku),
    agreed_price     numeric(10,2) NOT NULL,
    max_quantity     integer,                 -- NULL = без ліміту
    PRIMARY KEY (contract_number, product_sku),
    CONSTRAINT ck_contract_item_price CHECK (agreed_price >= 0),
    CONSTRAINT ck_contract_item_max   CHECK (max_quantity > 0)
);

CREATE TABLE warehouse (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL UNIQUE,
    address     text         NOT NULL,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz,
    updated_by  integer      REFERENCES app_user(id),
    deleted_at  timestamptz
);

-- Складений FK: товар має входити в контракт
CREATE TABLE supply (
    id               integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_number  varchar(50)   NOT NULL,
    product_sku      varchar(50)   NOT NULL,
    warehouse_id     integer       NOT NULL REFERENCES warehouse(id),
    delivery_date    date          NOT NULL,
    quantity         integer       NOT NULL,
    status           supply_status NOT NULL DEFAULT 'planned',
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz,
    updated_by       integer       REFERENCES app_user(id),
    CONSTRAINT ck_supply_quantity CHECK (quantity > 0),
    CONSTRAINT fk_supply_contract_item FOREIGN KEY (contract_number, product_sku)
        REFERENCES contract_item(contract_number, product_sku)
);

CREATE TABLE warehouse_stock (
    warehouse_id  integer     NOT NULL REFERENCES warehouse(id),
    product_sku   varchar(50) NOT NULL REFERENCES product(sku),
    quantity      integer     NOT NULL DEFAULT 0,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (warehouse_id, product_sku),
    CONSTRAINT ck_stock_quantity CHECK (quantity >= 0)
);
COMMENT ON TABLE warehouse_stock IS 'Залишки; змінюються лише тригерами supply та shipment';

CREATE TABLE shipment (
    id               integer         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number     integer         NOT NULL UNIQUE REFERENCES customer_order(order_number),
    warehouse_id     integer         NOT NULL REFERENCES warehouse(id),
    shipped_at       timestamptz,
    tracking_number  varchar(50),
    status           shipment_status NOT NULL DEFAULT 'pending',
    created_at       timestamptz     NOT NULL DEFAULT now(),
    updated_at       timestamptz,
    updated_by       integer         REFERENCES app_user(id)
);

CREATE TABLE audit_log (
    id          bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    table_name  varchar(63)  NOT NULL,
    record_id   varchar(100) NOT NULL,
    operation   varchar(12)  NOT NULL,
    old_data    jsonb,
    new_data    jsonb,
    changed_by  integer      REFERENCES app_user(id),
    changed_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_audit_operation CHECK
        (operation IN ('INSERT', 'UPDATE', 'DELETE', 'SOFT_DELETE', 'RESTORE'))
);
